const LABEL_KEYS = Object.fromEntries(
	Object.entries(MAP_TRANSLATIONS.en)
		.filter(([, value]) => !value.includes("{"))
		.map(([key, value]) => [value, key]),
);

// Localize known presentation labels without changing simulation enums or city names.
export function translateMapLabel(value, translate) {
	const label = String(value || "");
	if (Object.hasOwn(LABEL_KEYS, label)) return translate(LABEL_KEYS[label]);
	const side = /^Enemy Side (\d+)$/.exec(label);
	if (side) return translate("MAP_ENEMY_SIDE", { side: side[1] });
	const border = /^Neutral Border #(\d+)$/.exec(label);
	if (border) return translate("MAP_NEUTRAL_BORDER", { id: border[1] });
	return label;
}
